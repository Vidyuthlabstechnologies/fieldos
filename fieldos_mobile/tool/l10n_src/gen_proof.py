"""Writes lib/l10n/strings_proof_{hi,te,ta,kn,mr}.dart from proof_strings.tsv.

The TSV has one label per line: English, Hindi, Telugu, Tamil, Kannada,
Marathi, separated by tabs. Run from fieldos_mobile/:
    python3 tool/l10n_src/gen_proof.py
"""
import csv, os

HERE = os.path.dirname(__file__)
LANGS = ['hi', 'te', 'ta', 'kn', 'mr']
rows = []
with open(os.path.join(HERE, 'proof_strings.tsv'), encoding='utf-8') as f:
    for line in f:
        line = line.rstrip('\n')
        if not line or line.startswith('#'):
            continue
        parts = line.split('\t')
        assert len(parts) == 6, line
        rows.append(parts)

def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"

for i, lang in enumerate(LANGS, start=1):
    out = ['// Proof-of-value labels: cash book, pilot scorecard, RERA pack,',
           '// material check, entry history. Generated by tool/l10n_src/gen_proof.py.',
           '// ignore_for_file: lines_longer_than_80_chars', '',
           'const Map<String, String> proof%s = {' % lang.capitalize()]
    for r in sorted(rows, key=lambda r: r[0]):
        out.append('  %s: %s,' % (q(r[0]), q(r[i])))
    out.append('};')
    with open(os.path.join(HERE, '..', '..', 'lib', 'l10n', 'strings_proof_%s.dart' % lang), 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
print(len(rows), 'labels')
