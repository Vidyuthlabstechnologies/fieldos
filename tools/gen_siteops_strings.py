#!/usr/bin/env python3
"""Writes fieldos_mobile/lib/l10n/strings_siteops.dart from the tables in
tools/siteops_strings/*.py. Each table row is
English: (Hindi, Telugu, Tamil, Kannada, Marathi). Run from the repo root.
"""
import glob, importlib.util, os

rows = {}
for f in sorted(glob.glob(os.path.join(os.path.dirname(__file__), 'siteops_strings', 'part_*.py'))):
    spec = importlib.util.spec_from_file_location('p', f)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    for k, v in m.T.items():
        assert len(v) == 5, k
        rows[k] = v

def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"

out = ["// Pre-construction, site execution roles and consoles labels.", "// Generated by tools/gen_siteops_strings.py; edit the tables there.", "// ignore_for_file: lines_longer_than_80_chars", ""]
for i, lang in enumerate(['Hi', 'Te', 'Ta', 'Kn', 'Mr']):
    out.append(f"const Map<String, String> siteOps{lang} = {{")
    for k in sorted(rows):
        out.append(f"  {q(k)}: {q(rows[k][i])},")
    out.append("};")
    out.append("")
open(os.path.join(os.path.dirname(__file__), '..', 'fieldos_mobile', 'lib', 'l10n', 'strings_siteops.dart'), 'w').write("\n".join(out))
print(len(rows), 'labels')
